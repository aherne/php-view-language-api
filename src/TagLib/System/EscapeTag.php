<?php

namespace Lucinda\Templating\TagLib\System;

use Lucinda\Templating\History\SourceDocument;

/**
 * Protects literal template bodies during macro and expression expansion
 *
 * Each instance stores escaped source documents behind unique temporary placeholders.
 * Restoration reinserts the original bytes and source locations. Placeholder state
 * belongs to one compilation and is never shared through static fields.
 *
 * Tag syntax: <escape>literal body</escape>
 *
 * @see SourceDocument
 */
final class EscapeTag
{
    /**
     * @var array<int,SourceDocument> Literal source bodies indexed by their temporary placeholder number
     */
    private array $escapedDocuments = [];
    /**
     * Unique compilation-local prefix identifying placeholders owned by this instance
     */
    private string $placeholderPrefix;

    /**
     * Creates a compilation-local placeholder namespace for literal bodies
     *
     * @throws \Exception If the runtime cannot obtain randomness for the placeholder namespace
     */
    public function __construct()
    {
        $this->placeholderPrefix = "\x1A".bin2hex(random_bytes(16)).":";
    }

    /**
     * Protects escaped bodies in an untracked text string
     *
     * @param string $subject Template text containing zero or more escape blocks
     * @return string Text whose literal bodies have been replaced by private placeholders
     * @throws \Lucinda\Templating\ViewException If escape-block matching fails
     */
    public function backup(string $subject): string
    {
        return $this->backupDocument(new SourceDocument($subject))->getText();
    }

    /**
     * Stores escaped source fragments and substitutes temporary placeholders
     *
     * @param SourceDocument $subject Template document whose literal bodies must bypass parsing
     * @return SourceDocument Protected document; remaining text retains its source locations
     * @throws \Lucinda\Templating\ViewException If escape-block matching fails
     */
    public function backupDocument(SourceDocument $subject): SourceDocument
    {
        return $subject->replace('/<escape>(.*?)<\/escape>/si', function (array $matches, SourceDocument $match): string {
            $index = count($this->escapedDocuments);
            $this->escapedDocuments[$index] = $match->slice(strlen("<escape>"), strlen($matches[1]));
            return $this->placeholderPrefix.$index."\x1A";
        });
    }

    /**
     * Restores previously protected literal bodies into an untracked text string
     *
     * @param string $subject Text containing placeholders generated by this instance
     * @return string Text with literal escaped bodies restored
     * @throws \Lucinda\Templating\ViewException If placeholder matching fails
     */
    public function restore(string $subject): string
    {
        return $this->restoreDocument(new SourceDocument($subject))->getText();
    }

    /**
     * Restores literal body bytes together with their original source spans
     *
     * @param SourceDocument $subject Document containing placeholders generated by this instance
     * @return SourceDocument Document with escaped bodies reinserted at their placeholders
     * @throws \Lucinda\Templating\ViewException If placeholder matching fails
     */
    public function restoreDocument(SourceDocument $subject): SourceDocument
    {
        return $subject->replace('/'.preg_quote($this->placeholderPrefix, '/').'(\d+)\x1A/',
            fn(array $matches): SourceDocument => $this->escapedDocuments[(int) $matches[1]]);
    }
}
