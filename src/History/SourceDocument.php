<?php

namespace Lucinda\Templating\History;

use Lucinda\Templating\ViewException;

/**
 * Represents immutable template text together with its original file and line locations
 *
 * Literal spans advance through their original source lines. Generated spans stay
 * anchored to the directive that produced them. Slicing, concatenation and regex
 * replacement return new documents without changing the input document.
 *
 * Span keys are text and source (strings), line (one-based integer), and literal
 * (boolean). Location results contain only source and line.
 *
 * The compiler passes this concept between expansion stages so diagnostics do not
 * need markers in the text that will eventually be rendered.
 *
 * @see SourceMap
 * @see ViewLanguageParser
 */
final class SourceDocument
{
    /**
     * @var array<int,array<string,string|int|bool>> Ordered immutable text spans and their original source policy
     */
    private array $sourceSpans;

    /**
     * Creates template text associated with a source file and starting line
     *
     * @param string $text Literal or generated bytes; an empty string creates an empty document
     * @param string $source Original file path, or an empty string for untracked parser input
     * @param int $line One-based original starting line
     * @param bool $literal Whether newlines advance the original line instead of staying at one directive
     */
    public function __construct(string $text = "", string $source = "", int $line = 1, bool $literal = true)
    {
        $this->sourceSpans = $text === "" ? [] : [[
            "text"=>$text, "source"=>$source, "line"=>$line, "literal"=>$literal
        ]];
    }

    /**
     * Gets the concatenated document bytes without diagnostic instrumentation
     *
     * @return string Text represented by all source spans in order
     */
    public function getText(): string
    {
        return implode("", array_column($this->sourceSpans, "text"));
    }

    /**
     * Gets the ordered text spans and their source-location policies
     *
     * @return array<int,array<string,string|int|bool>> Literal or generated spans
     */
    public function getSpans(): array
    {
        return $this->sourceSpans;
    }

    /**
     * Creates a document containing this text followed by another document
     *
     * @param self $document Text to append with its existing source locations
     * @return self Concatenated document; neither input is modified
     */
    public function append(self $document): self
    {
        $result = clone $this;
        array_push($result->sourceSpans, ...$document->sourceSpans);
        return $result;
    }

    /**
     * Extracts a byte range while retaining its original source locations
     *
     * Literal spans adjust their starting line to the extracted position. Generated
     * spans remain anchored to the directive that created them.
     *
     * @param int $offset Nonnegative starting byte offset
     * @param int|null $length Maximum bytes to retain, or null to retain the remaining document
     * @return self Extracted document, possibly empty
     */
    public function slice(int $offset, ?int $length = null): self
    {
        $result = new self();
        $end = $length === null ? PHP_INT_MAX : $offset + $length;
        $position = 0;
        foreach ($this->sourceSpans as $span) {
            $size = strlen($span["text"]);
            $start = max(0, $offset - $position);
            $stop = min($size, $end - $position);
            if ($start < $stop) {
                if ($span["literal"]) {
                    $span["line"] += substr_count(substr($span["text"], 0, $start), "\n");
                }
                $span["text"] = substr($span["text"], $start, $stop - $start);
                $result->sourceSpans[] = $span;
            }
            $position += $size;
            if ($position >= $end) {
                break;
            }
        }
        return $result;
    }

    /**
     * Gets the original location corresponding to a document byte offset
     *
     * @param int $offset Nonnegative byte offset in the current document
     * @return array<string,string|int>|null Original location, or null for untracked or out-of-range input
     */
    public function getSourceLocation(int $offset = 0): ?array
    {
        $position = 0;
        foreach ($this->sourceSpans as $span) {
            $size = strlen($span["text"]);
            if ($offset < $position + $size) {
                return $span["source"] === "" ? null : [
                    "source"=>$span["source"],
                    "line"=>$span["line"] + ($span["literal"]
                        ? substr_count(substr($span["text"], 0, max(0, $offset - $position)), "\n") : 0)
                ];
            }
            $position += $size;
        }
        return null;
    }

    /**
     * Creates generated text anchored to a directive in this document
     *
     * @param string $text Replacement PHP or other generated bytes
     * @param int $offset Byte offset of the directive that produced the replacement
     * @return self Generated document whose lines all point to the directive location
     */
    public function createGeneratedDocument(string $text, int $offset = 0): self
    {
        $location = $this->getSourceLocation($offset);
        return new self($text, $location["source"] ?? "", $location["line"] ?? 1, false);
    }

    /**
     * Creates a template error associated with a document position
     *
     * @param string $message Diagnostic without an appended source location
     * @param int $offset Byte offset of the failing construct
     * @param \Throwable|null $previous Original failure to preserve in the exception chain
     * @return ViewException Error enriched with an available source file and line
     */
    public function createException(string $message, int $offset = 0, ?\Throwable $previous = null): ViewException
    {
        $location = $this->getSourceLocation($offset);
        return new ViewException($message, 0, $previous, $location);
    }

    /**
     * Replaces regex matches while preserving untouched and inserted source locations
     *
     * Callbacks receive capture strings, the matched document and its starting byte
     * offset. String results inherit the match location; document results retain their
     * own source spans. Parser errors without context gain the matched location.
     *
     * @param string $pattern Complete PCRE pattern evaluated against the input document
     * @param callable(array, self, int): (string|self) $callback Replacement operation for each match
     * @return self Document after all replacements, or this document when no matches occur
     * @throws ViewException If matching fails or a replacement reports a template error
     */
    public function replace(string $pattern, callable $callback): self
    {
        $text = $this->getText();
        $count = preg_match_all($pattern, $text, $matches, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
        if ($count === false) {
            throw new ViewException("Template pattern failed: ".preg_last_error_msg());
        }
        if ($count === 0) {
            return $this;
        }
        $result = new self();
        $cursor = 0;
        foreach ($matches as $match) {
            $offset = $match[0][1];
            $length = strlen($match[0][0]);
            $values = array_map(static fn(array $capture): string => $capture[0], $match);
            try {
                $replacement = $callback($values, $this->slice($offset, $length), $offset);
            } catch (ViewException $e) {
                if ($e->getSourceLocation() !== null) {
                    throw $e;
                }
                throw $this->createException($e->getMessage(), $offset, $e);
            }
            $result = $result->append($this->slice($cursor, $offset - $cursor));
            $result = $result->append($replacement instanceof self
                ? $replacement : $this->createGeneratedDocument($replacement, $offset));
            $cursor = $offset + $length;
        }
        return $result->append($this->slice($cursor));
    }

}
